// End-to-end check: pack the generator the way npm would, scaffold an app from the tarball, then install, type-check and build it.
//
//   pnpm test
//
// The app is installed and built with npm, which comes with Node; the other package managers are checked only for what the generator writes.
//
// The tests share one scaffolded app and each takes it further, so the suite runs with `concurrency: 1`. An early failure leaves the later tests nothing to work from — read the first failure, not the last.

import assert from 'node:assert/strict'
import { after, before, describe, test } from 'node:test'
import { execFileSync } from 'node:child_process'
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { tmpdir } from 'node:os'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = fileURLToPath(new URL('..', import.meta.url))

const APP_ID = 'app.example.e2e'
const APP_NAME = 'E2E'
const APP_AUTHOR = 'Nobody'
const APP_DESCRIPTION = 'Generated by the e2e test'

/** Files the built package must contain. */
const EXPECTED = ['appmeta/manifest.json', 'scripts/main.js']
/** Repository files that must never be packaged as app resources. */
const FORBIDDEN = ['resources/package.json', 'resources/README.md', 'resources/tsconfig.json']

/**
 * The environment without the npm_config_* variables of the package manager running the tests, plus the given ones.
 * @param {Record<string, string>} extra - Variables to set, e.g. the user agent the generator reads its package manager from.
 */
function env(extra = {}) {
  // npm reads those variables as its own config, and the generator would take the runner for the package manager to use.
  const own = Object.entries(process.env).filter(([key]) => !key.toLowerCase().startsWith('npm_config_'))
  return { ...Object.fromEntries(own), ...extra }
}

/** Runs a command, raising an error that carries the command's own output. With no user agent and no terminal, the generator installs with npm. */
function run(cmd, args, opts = {}) {
  try {
    return execFileSync(cmd, args, { encoding: 'utf8', stdio: 'pipe', env: env(), ...opts })
  } catch (err) {
    const output = [err.stdout, err.stderr].filter(Boolean).join('\n').trim()
    throw new Error(`${cmd} ${args.join(' ')} failed\n${output}`)
  }
}

describe('@busy-app/create-app', { concurrency: 1 }, () => {
  let work
  let appDir
  let tarball

  before(() => {
    work = mkdtempSync(resolve(tmpdir(), 'busy-create-app-'))
    appDir = resolve(work, 'my-app')
  })

  after(() => {
    rmSync(work, { recursive: true, force: true })
  })

  test('packs', () => {
    tarball = run('npm', ['pack', '--pack-destination', work], { cwd: ROOT }).trim().split('\n').pop()
    assert.ok(existsSync(resolve(work, tarball)), 'npm pack produced no tarball')
  })

  // From the tarball, so the tests see exactly the published file set.
  test('installs the generator from the tarball', () => {
    run('npm', ['install', '--no-save', '--silent', resolve(work, tarball)], { cwd: work })
    assert.ok(existsSync(resolve(work, 'node_modules/.bin/busy-create-app')))
  })

  test('scaffolds an app', () => {
    // Every field as a flag, so nothing is asked and stdin stays closed.
    run(
      resolve(work, 'node_modules/.bin/busy-create-app'),
      [
        'my-app',
        '--id', APP_ID,
        '--name', APP_NAME,
        '--description', APP_DESCRIPTION,
        '--author', APP_AUTHOR,
      ],
      { cwd: work, input: '' },
    )
    assert.ok(existsSync(appDir), 'the generator produced no app folder')
  })

  test('fills the placeholders in', () => {
    const manifest = JSON.parse(readFileSync(resolve(appDir, 'src/appmeta/manifest.json'), 'utf8'))
    assert.equal(manifest.id, APP_ID)
    assert.equal(manifest.name, APP_NAME)
    assert.equal(manifest.description, APP_DESCRIPTION)
    assert.equal(manifest.author, APP_AUTHOR)
    // Not passed, so the generator's default.
    assert.match(manifest.api_version, /^\d+\.\d+\.\d+$/)

    // Not asked for: the package is private, so the name comes from the folder.
    const pkg = JSON.parse(readFileSync(resolve(appDir, 'package.json'), 'utf8'))
    assert.equal(pkg.name, 'my-app')

    // npm strips .gitignore from tarballs; the generator restores it from _gitignore.
    for (const file of ['.gitignore', 'package.json', 'README.md']) {
      assert.ok(existsSync(resolve(appDir, file)), `${file} is missing`)
    }

    // grep exits 1 when it finds nothing — the outcome this test wants. node_modules/ is the generator's install, not the template.
    let left = ''
    try {
      left = execFileSync('grep', ['-rlE', '--exclude-dir=node_modules', '(^|[^$])\\{\\{', appDir], { encoding: 'utf8' }).trim()
    } catch (err) {
      if (err.status !== 1) throw err
    }
    assert.equal(left, '', `unfilled placeholders in:\n${left}`)
  })

  test('installs', () => {
    // The generator has installed already; a failure there is only reported, so it is checked here.
    assert.ok(existsSync(resolve(appDir, 'node_modules/.bin/busy-cli')), 'the generator installed no dependencies')
    // --engine-strict: the app pins a Node range, so a wrong version fails here rather than further down.
    run('npm', ['install', '--silent', '--engine-strict'], { cwd: appDir })
  })

  test('type-checks', () => {
    run('npm', ['run', 'typecheck'], { cwd: appDir })
  })

  test('builds a package', () => {
    run('npm', ['run', 'build'], { cwd: appDir })
    // The package folder is named after the manifest id.
    const dist = resolve(appDir, 'dist', APP_ID)

    for (const file of EXPECTED) {
      assert.ok(existsSync(resolve(dist, file)), `dist/${file} is missing`)
    }
    for (const file of FORBIDDEN) {
      assert.ok(!existsSync(resolve(dist, file)), `dist/${file} should not be packaged`)
    }

    // Only the app's own modules get a file of their own, and this one has none.
    assert.deepEqual(readdirSync(resolve(dist, 'scripts')), ['main.js'])
  })

  test('packages resources', () => {
    // A file in src/images/ lands in the package's images/; one loose in src/ is sorted by extension into the same place.
    mkdirSync(resolve(appDir, 'src/images'), { recursive: true })
    writeFileSync(resolve(appDir, 'src/images/icon.png'), '')
    writeFileSync(resolve(appDir, 'src/loose.png'), '')
    try {
      run('npm', ['run', 'build'], { cwd: appDir })
      for (const file of ['images/icon.png', 'images/loose.png']) {
        assert.ok(existsSync(resolve(appDir, 'dist', APP_ID, file)), `${file} is missing`)
      }
    } finally {
      rmSync(resolve(appDir, 'src/images'), { recursive: true, force: true })
      rmSync(resolve(appDir, 'src/loose.png'), { force: true })
    }
  })

  test('gives each app module its own chunk', () => {
    // Modules beside main.ts and in subfolders, each expected to be split out while shared/ and the dependencies stay inlined. Functions rather than constants: a lone constant is inlined and its chunk disappears.
    //
    // The two format.ts check that chunks named after the module's path under src/ keep same-named modules apart.
    mkdirSync(resolve(appDir, 'src/lib'), { recursive: true })
    mkdirSync(resolve(appDir, 'src/other'), { recursive: true })
    writeFileSync(
      resolve(appDir, 'src/greeting.ts'),
      'export function greeting(n: number): string {\n  return `Hi ${n}`;\n}\n',
    )
    writeFileSync(
      resolve(appDir, 'src/lib/format.ts'),
      'export function pad(n: number): string {\n  return String(n).padStart(2, "0");\n}\n',
    )
    writeFileSync(
      resolve(appDir, 'src/other/format.ts'),
      'export function wrap(s: string): string {\n  return `[${s}]`.repeat(1);\n}\n',
    )

    const main = resolve(appDir, 'src/main.ts')
    const original = readFileSync(main, 'utf8')
    const patched = original.replace('text: "Hello"', 'text: wrap(greeting(ticks)) + pad(ticks)')
    assert.notEqual(patched, original, 'the test could not patch main.ts')
    writeFileSync(
      main,
      'import { greeting } from "./greeting.ts";\n' +
        'import { pad } from "./lib/format.ts";\n' +
        'import { wrap } from "./other/format.ts";\n' +
        patched,
    )

    try {
      run('npm', ['run', 'typecheck'], { cwd: appDir })
      run('npm', ['run', 'build'], { cwd: appDir })

      assert.deepEqual(readdirSync(resolve(appDir, 'dist', APP_ID, 'scripts')).sort(), [
        'greeting.js',
        'lib-format.js',
        'main.js',
        'other-format.js',
      ])
      // Same name, different folders: the two must not be merged.
      const lib = readFileSync(resolve(appDir, 'dist', APP_ID, 'scripts/lib-format.js'), 'utf8')
      assert.match(lib, /padStart/, 'lib-format.js lost its module')
    } finally {
      writeFileSync(main, original)
      rmSync(resolve(appDir, 'src/greeting.ts'), { force: true })
      rmSync(resolve(appDir, 'src/lib'), { recursive: true, force: true })
      rmSync(resolve(appDir, 'src/other'), { recursive: true, force: true })
    }
  })

  test('rejects an export in the entry', () => {
    const main = resolve(appDir, 'src/main.ts')
    const original = readFileSync(main, 'utf8')
    writeFileSync(main, original.replace('function main()', 'export default function main()'))
    try {
      assert.throws(() => run('npm', ['run', 'build'], { cwd: appDir }), /must not export anything/)
    } finally {
      writeFileSync(main, original)
    }
  })

  test('redirects the build with --out', () => {
    run('npm', ['run', 'build', '--', '--out', '../elsewhere'], { cwd: appDir })
    assert.ok(
      existsSync(resolve(work, 'elsewhere', APP_ID, 'scripts/main.js')),
      '--out did not redirect the build',
    )
  })

  test('packs a tgz alongside the folder with --tgz', () => {
    run('npm', ['run', 'build', '--', '--tgz'], { cwd: appDir })
    const dist = resolve(appDir, 'dist')

    assert.ok(existsSync(resolve(dist, `${APP_ID}.tgz`)), 'the archive is missing')
    assert.ok(existsSync(resolve(dist, APP_ID, 'scripts/main.js')), '--tgz dropped the folder')

    // The archive holds the <id>/ folder itself, ready to unpack as-is.
    const listing = run('tar', ['-tzf', resolve(dist, `${APP_ID}.tgz`)])
    assert.match(listing, new RegExp(`^${APP_ID}/appmeta/manifest\\.json$`, 'm'))
    assert.match(listing, new RegExp(`^${APP_ID}/scripts/main\\.js$`, 'm'))
  })

  test('leaves only the tgz with --tgz-only', () => {
    run('npm', ['run', 'build', '--', '--tgz-only'], { cwd: appDir })
    const dist = resolve(appDir, 'dist')

    assert.ok(existsSync(resolve(dist, `${APP_ID}.tgz`)), 'the archive is missing')
    assert.ok(!existsSync(resolve(dist, APP_ID)), '--tgz-only left the folder behind')
  })

  test('names the tgz with --tgz-name', () => {
    run('npm', ['run', 'build', '--', '--tgz-only', '--tgz-name', '{id}-{version}.tgz'], { cwd: appDir })
    const manifest = JSON.parse(readFileSync(resolve(appDir, 'src/appmeta/manifest.json'), 'utf8'))
    const archive = `${APP_ID}-${manifest.version}.tgz`

    assert.ok(existsSync(resolve(appDir, 'dist', archive)), `${archive} is missing`)
    // The name changes, the folder inside does not.
    const listing = run('tar', ['-tzf', resolve(appDir, 'dist', archive)])
    assert.match(listing, new RegExp(`^${APP_ID}/scripts/main\\.js$`, 'm'))
  })

  test('rejects an id longer than 32 characters', () => {
    const tooLong = `app.example.${'x'.repeat(32)}`
    assert.throws(
      () =>
        run(resolve(work, 'node_modules/.bin/busy-create-app'), ['long', '--author', APP_AUTHOR, '--id', tooLong], {
          cwd: work,
          input: '',
        }),
      /32 characters/,
    )
  })

  test('takes a dash in the id', () => {
    const dir = resolve(work, 'dashed')
    run(
      resolve(work, 'node_modules/.bin/busy-create-app'),
      ['dashed', '--id', 'app.example.my-app', '--name', 'N', '--description', 'd', '--author', APP_AUTHOR, '--no-git', '--no-install'],
      { cwd: work, input: '' },
    )
    const manifest = JSON.parse(readFileSync(resolve(dir, 'src/appmeta/manifest.json'), 'utf8'))
    assert.equal(manifest.id, 'app.example.my-app')
  })

  // The firmware rejects these, so the generator does too.
  test('rejects a leading dot or a non-Latin letter in the id', () => {
    for (const [dir, id] of [['leading-dot', '.app.example.x'], ['non-latin', 'app.example.приложение']]) {
      assert.throws(
        () =>
          run(resolve(work, 'node_modules/.bin/busy-create-app'), [dir, '--author', APP_AUTHOR, '--id', id], {
            cwd: work,
            input: '',
          }),
        /only Latin letters/,
      )
    }
  })

  test('takes the API version from --api-version', () => {
    const dir = resolve(work, 'api')
    run(
      resolve(work, 'node_modules/.bin/busy-create-app'),
      ['api', '--id', 'app.example.api', '--name', 'Api', '--description', 'd', '--author', APP_AUTHOR, '--api-version', '1.2.3', '--no-git', '--no-install'],
      { cwd: work, input: '' },
    )
    const manifest = JSON.parse(readFileSync(resolve(dir, 'src/appmeta/manifest.json'), 'utf8'))
    assert.equal(manifest.api_version, '1.2.3')
  })

  test('rejects a malformed --api-version', () => {
    assert.throws(
      () =>
        run(resolve(work, 'node_modules/.bin/busy-create-app'), ['bad-api', '--author', APP_AUTHOR, '--api-version', '27.12'], {
          cwd: work,
          input: '',
        }),
      /x\.y\.z/,
    )
  })

  test('keeps a dash and turns a space in the folder name into an underscore', () => {
    for (const [dir, id] of [['dashed-name', 'app.nobody.dashed-name'], ['spaced name', 'app.nobody.spaced_name']]) {
      run(
        resolve(work, 'node_modules/.bin/busy-create-app'),
        [dir, '--name', 'N', '--description', 'd', '--author', APP_AUTHOR, '--no-git', '--no-install'],
        { cwd: work, input: '' },
      )
      const manifest = JSON.parse(readFileSync(resolve(work, dir, 'src/appmeta/manifest.json'), 'utf8'))
      assert.equal(manifest.id, id)
    }
  })

  test('falls back to a placeholder app part', () => {
    // A character the firmware rejects in the folder name; the author's namespace stays.
    run(
      resolve(work, 'node_modules/.bin/busy-create-app'),
      ['my app (2)', '--name', 'N', '--description', 'd', '--author', APP_AUTHOR, '--no-git', '--no-install'],
      { cwd: work, input: '' },
    )
    const manifest = JSON.parse(readFileSync(resolve(work, 'my app (2)', 'src/appmeta/manifest.json'), 'utf8'))
    assert.equal(manifest.id, 'app.nobody.app')
  })

  test('leaves the repository out with --no-git', () => {
    const dir = resolve(work, 'no-git')
    run(
      resolve(work, 'node_modules/.bin/busy-create-app'),
      ['no-git', '--id', 'app.example.no_git', '--name', 'No Git', '--description', 'd', '--author', APP_AUTHOR, '--no-git', '--no-install'],
      { cwd: work, input: '' },
    )
    assert.ok(existsSync(resolve(dir, 'src/main.ts')), 'the app is missing')
    assert.ok(!existsSync(resolve(dir, '.git')), '--no-git still initialized a repository')
  })

  test('falls back to a placeholder namespace', () => {
    // A letter the firmware rejects in one author, an apostrophe in another, too many characters in the last.
    for (const [dir, author] of [['cyrillic', 'Иван'], ['apostrophe', "O'Brien"], ['lengthy', 'A Remarkably Long Author Name']]) {
      run(
        resolve(work, 'node_modules/.bin/busy-create-app'),
        [dir, '--author', author, '--name', 'N', '--description', 'd', '--no-git', '--no-install'],
        { cwd: work, input: '' },
      )
      const manifest = JSON.parse(readFileSync(resolve(work, dir, 'src/appmeta/manifest.json'), 'utf8'))
      assert.equal(manifest.id, `app.example.${dir}`)
    }
  })

  test('leaves the dependencies out with --no-install', () => {
    // Scaffolded with --no-install by the test above.
    assert.ok(!existsSync(resolve(work, 'no-git', 'node_modules')), '--no-install still installed the dependencies')
  })

  test('defaults to a namespace made from the author', () => {
    const dir = resolve(work, 'defaults')
    // --author: its prompt falls back to `git config user.name`, which CI has no value for.
    run(resolve(work, 'node_modules/.bin/busy-create-app'), ['defaults', '--author', APP_AUTHOR, '--no-install'], {
      cwd: work,
      // Enter through every prompt; spare newlines are harmless.
      input: '\n'.repeat(8),
    })
    const manifest = JSON.parse(readFileSync(resolve(dir, 'src/appmeta/manifest.json'), 'utf8'))
    assert.equal(manifest.id, 'app.nobody.defaults')
  })

  describe('package managers', () => {
    /** What each launcher spells into the app: the user agent it runs the generator under, and the packageManager field only Yarn 2+ gets. */
    const CASES = [
      { name: 'npm', pm: 'npm', agent: 'npm/11.13.0 node/v24.16.0 linux x64 workspaces/false', build: 'npm run build', withArgs: 'npm run build -- --tgz', ci: 'npm ci' },
      { name: 'pnpm', pm: 'pnpm', agent: 'pnpm/11.4.0 npm/? node/v24.16.0 linux x64', build: 'pnpm build', withArgs: 'pnpm build --tgz', ci: 'pnpm install --frozen-lockfile' },
      { name: 'yarn 1', pm: 'yarn', agent: 'yarn/1.22.22 npm/? node/v24.16.0 linux x64', build: 'yarn build', withArgs: 'yarn build --tgz', ci: 'yarn install --frozen-lockfile' },
      { name: 'yarn 4', pm: 'yarn', agent: 'yarn/4.9.1 npm/? node/v24.16.0 linux x64', build: 'yarn build', withArgs: 'yarn build --tgz', ci: 'yarn install --immutable', field: 'yarn@4.9.1' },
      { name: 'bun', pm: 'bun', agent: 'bun/1.2.2 npm/? node/v24.16.0 linux x64', build: 'bun run build', withArgs: 'bun run build --tgz', ci: 'bun install --frozen-lockfile' },
    ]

    /** Scaffolds `<dir>` without git or an install, so no package manager has to be present. */
    const scaffold = (dir, extraEnv) =>
      run(
        resolve(work, 'node_modules/.bin/busy-create-app'),
        [dir, '--author', APP_AUTHOR, '--name', 'N', '--description', 'd', '--no-git', '--no-install'],
        { cwd: work, input: '', env: env(extraEnv) },
      )

    const packageManagerField = (dir) => JSON.parse(readFileSync(resolve(work, dir, 'package.json'), 'utf8')).packageManager

    for (const { name, pm, agent, build, withArgs, ci, field } of CASES) {
      test(`spells the app for ${name}, the launcher`, () => {
        const dir = `pm-${name.replace(' ', '')}`
        const output = scaffold(dir, { npm_config_user_agent: agent })

        assert.match(output, new RegExp(`^  ${pm} install$`, 'm'), 'the hint does not install with it')
        assert.match(output, new RegExp(`^  ${build}$`, 'm'), 'the hint does not build with it')

        const readme = readFileSync(resolve(work, dir, 'README.md'), 'utf8')
        assert.ok(readme.includes(`\`${build}\``), `README lacks ${build}`)
        assert.ok(readme.includes(`\`${withArgs}\``), `README lacks ${withArgs}`)

        for (const workflow of ['ci.yml', 'release.yml']) {
          const text = readFileSync(resolve(work, dir, '.github/workflows', workflow), 'utf8')
          assert.match(text, new RegExp(`- run: ${ci}$`, 'm'), `${workflow} does not install with ${name}`)
          // Steps sit under steps:, or the workflow does not parse.
          assert.match(text, /^ {6}- uses: actions\/setup-node@v6$/m, `${workflow} lost the step indentation`)
        }

        // Yarn 2+ would otherwise switch to Plug'n'Play and refuse to install inside another project.
        assert.equal(existsSync(resolve(work, dir, '.yarnrc.yml')), pm === 'yarn', '.yarnrc.yml')
        assert.equal(existsSync(resolve(work, dir, 'yarn.lock')), pm === 'yarn', 'yarn.lock')
        // Only Yarn 2+ needs telling apart from the Yarn 1 a CI runner has.
        assert.equal(packageManagerField(dir), field)
      })
    }

    test('falls back to npm without a launcher', () => {
      assert.match(scaffold('pm-none'), /^ {2}npm run build$/m)
    })

    test('falls back to npm for an unsupported launcher', () => {
      assert.match(scaffold('pm-deno', { npm_config_user_agent: 'deno/2.1.4 npm/? deno/2.1.4 linux x64' }), /^ {2}npm run build$/m)
    })
  })
})
